// 實機測試：送到 Bambu Studio（需已安裝 Bambu Studio）
import { launch, close, sleep } from './lib.mjs';
import { mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { tmpdir, homedir } from 'node:os';
import { execFileSync } from 'node:child_process';
const PROFILE = 'e2e-bambu';
const out = join(tmpdir(), 'xiaoke-3d-e2e-bambu');
rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });
const ud = join(process.env.APPDATA || join(homedir(), 'AppData/Roaming'), `xiaoke-3d-${PROFILE}`);
mkdirSync(ud, { recursive: true });
writeFileSync(join(ud, 'settings.json'), JSON.stringify({ exportDir: out }));
const { app, win } = await launch(PROFILE);
const until = async (fn, ms = 90000) => { const t0 = Date.now(); while (Date.now() - t0 < ms) { const v = await win.evaluate(fn).catch(() => null); if (v) return v; await sleep(300); } return null; };
await until(() => document.getElementById('loading').classList.contains('hidden'));
console.log('Bambu 狀態：', (await win.textContent('#bambuStatus')).trim());
await win.click('.tpl-card[data-id="cup"]');
await win.click('#tplCreate');
await until(() => /已建立「杯子／筆筒」/.test(document.getElementById('status').textContent));
await win.fill('#fileName', '小柯杯子');
await win.click('#btnBambu');
const st = await until(() => { const s = document.getElementById('status').textContent; return /已送到 Bambu Studio|無法開啟|失敗/.test(s) && s; });
console.log('狀態列：', st);
await sleep(8000);
const ps = execFileSync('powershell', ['-NoProfile', '-Command', "[Console]::OutputEncoding=[Text.Encoding]::UTF8; Get-CimInstance Win32_Process -Filter \"Name='bambu-studio.exe'\" | ForEach-Object { \"$($_.ProcessId)|$($_.CommandLine)\" }"], { encoding: 'utf8' }).trim();
console.log('Bambu Studio 程序：', ps || '（沒有）');
await close(app);
process.exit(/已送到/.test(st || '') && /小柯杯子\.3mf/.test(ps) ? 0 : 1);
